/**
 * tailwind.config.ts
 *
 * WHY THIS FILE?
 * Tailwind is a utility-first CSS framework — it generates only the CSS classes
 * actually used in your code. The `content` array tells Tailwind which files to
 * scan. Any file not listed here won't have its classes included in the build.
 *
 * The `darkMode: 'class'` setting means dark mode is toggled by adding the
 * `dark` class to <html>, which we do in the root layout. This gives full
 * control rather than relying on the user's OS preference.
 *
 * The `theme.extend` block adds to (not replaces) Tailwind's defaults.
 * We extend `colors` to map shadcn/ui's CSS variables into Tailwind classes,
 * so `bg-primary`, `text-muted-foreground` etc. all work correctly.
 */

